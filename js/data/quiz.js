const ri = (rng, a, b) => a + Math.floor(rng() * (b - a + 1));
const pick = (rng, xs) => xs[Math.floor(rng() * xs.length)];
export const shuffle = (rng, xs) => { const a = [...xs]; for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(rng() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; };

// ---- さんすう ----
// くりあがりの ある たしざん：1けた ＋ 1けた で 11〜18
function add(rng) {
  let a, b;
  do { a = ri(rng, 2, 9); b = ri(rng, 2, 9); } while (a + b < 11);
  return { cat: 'add', kind: 'num', text: `${a} ＋ ${b}`, answer: a + b };
}
// くりさがりの ある ひきざん：11〜18 − 1けた（一のくらいから ひけない）
function sub(rng) {
  let a, b;
  do { a = ri(rng, 11, 18); b = ri(rng, 2, 9); } while (a % 10 >= b);
  return { cat: 'sub', kind: 'num', text: `${a} − ${b}`, answer: a - b };
}
// 3つの かずの けいさん：とちゅうも こたえも 0〜20。はんぶんは とちゅうで 10に なる（10 − 3 − 2・4 ＋ 6 ＋ 3）
function three(rng) {
  const ten = rng() < 0.5;
  for (;;) {
    const op1 = rng() < 0.5 ? '+' : '-', op2 = rng() < 0.5 ? '+' : '-';
    const a = op1 === '+' ? ri(rng, 1, 9) : ri(rng, 10, 18), b = ri(rng, 1, 9), c = ri(rng, 1, 9);
    const r1 = op1 === '+' ? a + b : a - b, r2 = op2 === '+' ? r1 + c : r1 - c;
    if (r1 < 0 || r1 > 20 || r2 < 0 || r2 > 20 || (ten && r1 !== 10)) continue;
    const sym = (o) => (o === '+' ? '＋' : '−');
    return { cat: 'three', kind: 'num', text: `${a} ${sym(op1)} ${b} ${sym(op2)} ${c}`, answer: r2 };
  }
}
// 10の まとまり（いくつと いくつ）：10は 7と □、□と 4で 10。ときどき 5〜9 も
function ten(rng) {
  const n = rng() < 0.7 ? 10 : ri(rng, 5, 9), a = ri(rng, 1, n - 1);
  return rng() < 0.5
    ? { cat: 'ten', kind: 'num', text: `${n}は ${a}と □`, answer: n - a }
    : { cat: 'ten', kind: 'num', text: `□と ${a}で ${n}`, answer: n - a };
}
// とけい：なんじ・なんじはん。まちがえ やすい ものを えらびに 入れる（はんの ときは はりの ちかい ほうの「つぎの じ」）
export const clockLabel = (h, m) => `${h}じ${m ? 'はん' : ''}`;
const hr = (x) => ((x + 11) % 12) + 1; // 0 → 12、13 → 1
function clock(rng) {
  const h = ri(rng, 1, 12), m = rng() < 0.5 ? 0 : 30;
  const answer = clockLabel(h, m);
  const first = m ? [clockLabel(hr(h + 1), 30)] : h !== 12 ? [clockLabel(12, 0)] : [];
  const rest = shuffle(rng, [clockLabel(h, 30 - m), clockLabel(hr(h + 1), m), clockLabel(hr(h - 1), m), clockLabel(hr(h + 1), 30 - m), clockLabel(hr(h - 1), 30 - m)]);
  const wrong = [...new Set([...first, ...rest])].filter((x) => x !== answer).slice(0, 3);
  return { cat: 'clock', kind: 'choice', text: 'とけいは なんじ？', clock: [h, m], answer, choices: shuffle(rng, [answer, ...wrong]) };
}

