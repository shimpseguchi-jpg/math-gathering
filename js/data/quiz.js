export const GEN = { add, sub, three, ten, clock, kanji, particle };

// つぎの もんだい：えらんだ しゅるいを おもさの ぶんだけ ふくろに 入れて、まぜて じゅんばんに 出す（おなじ もんだいは つづけない）
export function quizSession(rng, cats = Object.keys(CATS)) {
  let bag = [];
  const recent = [];
  return () => {
    if (!bag.length) bag = shuffle(rng, cats.flatMap((c) => Array(CATS[c].weight).fill(c)));
    const cat = bag.pop();
    let q;
    for (let i = 0; i < 20; i++) { q = GEN[cat](rng); if (!recent.includes(q.text + q.answer)) break; }
    recent.push(q.text + q.answer); if (recent.length > 12) recent.shift();
    return q;
  };
}

